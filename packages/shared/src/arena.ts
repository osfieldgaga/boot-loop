/** Exposed ledges with room for the full bobbing pickup visual, away from spawn pads. */
export function arenaPickupSpots(world: WorldMap): { x: number; y: number }[] {
  const spots: { x: number; y: number }[] = [];
  for (let row = 3; row < world.height - 2; row++) {
    for (let col = 3; col < world.width - 3; col++) {
      if (!isSolid(world, col, row) || isSolid(world, col, row - 1)) continue;
      const spot = { x: col * 8, y: row * 8 - 12 };
      if (overlapsSolid(world, spot.x - 3, spot.y - 4, 14, 16)) continue;
      if (world.spawns.some(s => Math.hypot(s.x - spot.x, s.y - spot.y) <= 24)) continue;
      if (spots.some(s => Math.hypot(s.x - spot.x, s.y - spot.y) < 32)) continue;
      spots.push(spot);
    }
  }
  return spots;
}
